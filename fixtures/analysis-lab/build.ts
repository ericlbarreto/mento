// Analysis lab builder: scripts.json → conversations.json (contract-shaped sessions, events and evidence).
// Run: pnpm exec tsx fixtures/analysis-lab/build.ts
// Shapes follow workstreams/contracts-spec.md §2–5 and are validated with the Zod schemas from @mento/contracts.
// The analysis input, rules and insights are NOT built here: they come from @mento/analysis.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ConversationFile, normalizeConcept } from "../../packages/contracts/src";

const here = dirname(fileURLToPath(import.meta.url));
const read = (f: string) => JSON.parse(readFileSync(join(here, f), "utf8"));

type Hint = { level: 1 | 2 | 3; text: string; student_before?: string };
type Verify = {
  concept: string; lesson_id: string; question: string; answer: string;
  result: "correct" | "partial" | "incorrect"; rationale: string; hints?: Hint[];
};
type Step =
  | { student: string }
  | { tutor: string; cite?: { page: number; quote: string } }
  | { verify: Verify };
type Script = {
  id: string; student_id: string; lesson_id: string | null; topic: string; started_at: string;
  end_reason: "user_left" | "idle_timeout" | "beacon" | "manual"; steps: Step[];
};

const SECONDS_PER_EVENT = 20;
const scripts = read("scripts.json");
const material = read("material.json");

function buildSession(s: Script) {
  const events: Record<string, unknown>[] = [];
  const evidence: Record<string, unknown>[] = [];
  const start = Date.parse(s.started_at);
  let turn = 0;
  let verifications = 0;
  const push = (type: string, payload: Record<string, unknown>) => {
    const seq = events.length + 1;
    const e = {
      id: `${s.id}_e${String(seq).padStart(2, "0")}`,
      session_id: s.id,
      seq,
      ts: new Date(start + (seq - 1) * SECONDS_PER_EVENT * 1000).toISOString(),
      type,
      payload,
    };
    events.push(e);
    return e;
  };
  const speak = (text: string, extra: Record<string, unknown> = {}) => {
    turn += 1;
    return push("tutor_action", {
      turn_id: `turn_${turn}`, action_id: `act_${turn}_1`, order: 1, name: "speak", args: { text, ...extra },
    });
  };

  push("session_started", { student_id: s.student_id, material_id: material.id, lesson_id: s.lesson_id, topic: s.topic, modality: "text" });
  for (const step of s.steps) {
    if ("student" in step) push("user_message", { kind: "chat", text: step.student });
    else if ("tutor" in step) {
      speak(step.tutor, step.cite ? { purpose: "explain", sources: [{ material_id: material.id, ...step.cite }] } : { purpose: "explain" });
    } else {
      const v = step.verify;
      verifications += 1;
      const verification_id = `ver_${s.id}_${verifications}`;
      const concept_key = normalizeConcept(v.concept);
      speak(v.question, { purpose: "question" });
      push("verification_asked", { verification_id, element_id: `el_q${verifications}`, concept: v.concept, concept_key, lesson_id: v.lesson_id, question: v.question, kind: "open" });
      // hints_used and independent are computed from hint_given events (contracts-spec §5), never written by hand.
      let hints_used = 0;
      for (const h of v.hints ?? []) {
        if (h.student_before) push("user_message", { kind: "chat", text: h.student_before });
        speak(h.text, { purpose: "hint", hint_level: h.level });
        push("hint_given", { turn_id: `turn_${turn}`, level: h.level, verification_id, concept_key });
        hints_used += 1;
      }
      const answered = push("verification_answered", { verification_id, element_id: `el_q${verifications}`, answer: v.answer });
      const evidence_id = `evd_${s.id}_${verifications}`;
      const independent = hints_used === 0;
      evidence.push({
        id: evidence_id, session_id: s.id, student_id: s.student_id, concept: v.concept, concept_key,
        lesson_id: v.lesson_id, result: v.result, independent, hints_used, rationale: v.rationale, ts: answered.ts,
      });
      push("evidence_recorded", { evidence_id, verification_id, concept: v.concept, concept_key, result: v.result, independent, hints_used, rationale: v.rationale });
    }
  }
  const ended = push("session_ended", { reason: s.end_reason });
  return {
    id: s.id, student_id: s.student_id, material_id: material.id, lesson_id: s.lesson_id, topic: s.topic, modality: "text",
    status: "ended", started_at: s.started_at, ended_at: ended.ts as string, end_reason: s.end_reason, is_simulated: true,
    events, evidence,
  };
}

const sessions = (scripts.conversations as Script[]).map(buildSession);
// Fail loudly if a script produces anything the contract does not allow.
const file = ConversationFile.parse({ sessions });
writeFileSync(join(here, "conversations.json"), JSON.stringify({ _note: "GENERATED by build.ts from scripts.json — do not edit by hand.", sessions: file.sessions }, null, 2) + "\n");
console.log(`built ${file.sessions.length} sessions, ${file.sessions.reduce((a, s) => a + s.events.length, 0)} events`);
