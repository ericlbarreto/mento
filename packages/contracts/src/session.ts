import { z } from "zod";
import { Evidence } from "./evidence";
import { SessionEndReason, SessionEvent } from "./session-events";

/** A tutoring conversation. `lesson_id` = the lesson of `material.sequence` the student is studying. */
export const Session = z.object({
  id: z.string(),
  student_id: z.string(),
  /** The material the conversation used (derived from the sources the tutor cited); `null` when it cited none. */
  material_id: z.string().nullable(),
  /** The lesson being studied (derived from the cited pages); `null` when unknown. */
  lesson_id: z.string().nullable().default(null),
  /** The subject the student started it from (`null` = free whiteboard). Absent when the source does not record it (lab fixtures). */
  subject_id: z.string().nullable().optional(),
  topic: z.string().optional(),
  persona: z.string().optional(),
  modality: z.enum(["text", "voice"]),
  status: z.enum(["active", "ended"]),
  started_at: z.string(),
  ended_at: z.string().optional(),
  end_reason: SessionEndReason.optional(),
  is_simulated: z.boolean().default(false),
});
export type Session = z.infer<typeof Session>;

export const SessionBundle = z.object({
  session: Session,
  events: z.array(SessionEvent),
  evidence: z.array(Evidence),
});
export type SessionBundle = z.infer<typeof SessionBundle>;

/** Shape of `fixtures/analysis-lab/conversations.json` (generated by build.ts). */
export const ConversationFile = z.object({
  sessions: z.array(Session.extend({ events: z.array(SessionEvent), evidence: z.array(Evidence) })),
});
export type ConversationFile = z.infer<typeof ConversationFile>;
